// Vectors generated by the official Python SDK (scripts/hyperliquid-vectors.py in the Candle repo).
interface L1Vector {
  name: string
  kind: string
  action: Record<string, unknown>
  nonce: number
  msgpackHex: string
  actionHash: string
}
const l1 = (fixture.cases as unknown as L1Vector[]).filter((c) => c.kind === "l1")
const hex = (bytes: Uint8Array) => Buffer.from(bytes).toString("hex")

describe("encoding matches the official Python SDK", () => {
  test("there are vectors for every action type Candle builds", () => {
    const types = new Set(l1.map((c) => c.action.type))
    for (const type of ["order", "cancel", "modify", "updateLeverage", "updateIsolatedMargin"]) {
      expect(types.has(type)).toBe(true)
    }
  })
  for (const vector of l1) {
    test(`${vector.name}: msgpack and action hash`, () => {
      expect(hex(msgpackEncode(vector.action))).toBe(vector.msgpackHex)
      expect(hyperliquidActionHash(vector.action, vector.nonce)).toBe(vector.actionHash)
    })
  }
})

const BUILDER = "0x7a2b3c4d5e6f708192a3b4c5d6e7f80910a1b2c3"
const OTHER = "0x1111111111111111111111111111111111111111"

function orderBuild(overrides: Partial<PerpsBuildToVerify> = {}, action?: Record<string, unknown>): PerpsBuildToVerify {
  const a = action ?? {
    type: "order",
    orders: [
      { a: 0, b: true, p: "60000", s: "0.01", r: false, t: { limit: { tif: "Gtc" } }, c: `0x${"1".repeat(32)}` },
    ],
    grouping: "na",
    builder: { b: BUILDER, f: 100 },
  }
  const nonce = overrides.nonce ?? 1_790_000_000_000
  return {
    network: "mainnet",
    nonce,
    action: a,
    typedData: hyperliquidL1TypedData(hyperliquidActionHash(a, nonce), "mainnet"),
    ...overrides,
  }
}

describe("verifyPerpsBuild refuses before any relay call", () => {
  test("an honest order passes", () => {
    expect(verifyPerpsBuild(orderBuild(), { builder: BUILDER })).toEqual({ ok: true, kind: "l1" })
  })

  test("an order with no builder (a Max order) passes", () => {
    const action = { type: "order", orders: [], grouping: "na" }
    expect(verifyPerpsBuild(orderBuild({}, action), { builder: BUILDER }).ok).toBe(true)
  })

  test("an action type Candle does not build: vaultTransfer, withdraw3, usdSend, approveAgent, subAccountTransfer", () => {
    for (const type of [
      "vaultTransfer",
      "withdraw3",
      "usdSend",
      "approveAgent",
      "subAccountTransfer",
      "createSubAccount",
    ]) {
      const result = verifyPerpsBuild(orderBuild({}, { type, vaultAddress: OTHER, isDeposit: true, usd: 1 }), {
        builder: BUILDER,
      })
      expect(result.ok).toBe(false)
    }
  })

  test("a builder that is not Candle's, or a fee over 0.1%", () => {
    const wrong = { type: "order", orders: [], grouping: "na", builder: { b: OTHER, f: 100 } }
    expect(verifyPerpsBuild(orderBuild({}, wrong), { builder: BUILDER }).ok).toBe(false)
    const greedy = { type: "order", orders: [], grouping: "na", builder: { b: BUILDER, f: 101 } }
    expect(verifyPerpsBuild(orderBuild({}, greedy), { builder: BUILDER }).ok).toBe(false)
    const cancelWithBuilder = { type: "cancel", cancels: [{ a: 0, o: 1 }], builder: { b: BUILDER, f: 1 } }
    expect(verifyPerpsBuild(orderBuild({}, cancelWithBuilder), { builder: BUILDER }).ok).toBe(false)
  })

  test("typed data that does not commit to the plaintext action or nonce", () => {
    const honest = orderBuild()
    const swapped = { ...honest, action: { ...honest.action, grouping: "normalTpsl" } }
    expect(verifyPerpsBuild(swapped, { builder: BUILDER }).ok).toBe(false)
    expect(verifyPerpsBuild({ ...honest, nonce: honest.nonce + 1 }, { builder: BUILDER }).ok).toBe(false)
  })

  test("the wrong network or source, a different domain, an extra key", () => {
    const honest = orderBuild()
    expect(verifyPerpsBuild(honest, { builder: BUILDER, network: "testnet" }).ok).toBe(false)
    const testnetTyped = {
      ...honest,
      network: undefined,
      typedData: hyperliquidL1TypedData(String(honest.typedData.message.connectionId), "testnet"),
    }
    expect(verifyPerpsBuild(testnetTyped, { builder: BUILDER }).ok).toBe(false)
    const otherChain = {
      ...honest,
      typedData: { ...honest.typedData, domain: { ...honest.typedData.domain, chainId: 1 } },
    }
    expect(verifyPerpsBuild(otherChain, { builder: BUILDER }).ok).toBe(false)
    const extra = { ...honest, typedData: { ...honest.typedData, message: { ...honest.typedData.message, extra: 1 } } }
    expect(verifyPerpsBuild(extra, { builder: BUILDER }).ok).toBe(false)
    const otherType = { ...honest, typedData: { ...honest.typedData, primary_type: "HyperliquidTransaction:Withdraw" } }
    expect(verifyPerpsBuild(otherType, { builder: BUILDER }).ok).toBe(false)
  })

  test("a build for a different wallet", () => {
    expect(verifyPerpsBuild(orderBuild({ address: OTHER }), { builder: BUILDER, address: BUILDER }).ok).toBe(false)
  })

  test("no builder to check against is a refusal, not a pass", () => {
    expect(verifyPerpsBuild(orderBuild(), { builder: "" }).ok).toBe(false)
    expect(verifyPerpsBuild(orderBuild(), { builder: `0x${"0".repeat(40)}` }).ok).toBe(false)
  })
})

describe("take-profit and stop-loss limit prices are held to their triggers", () => {
  const order = (b: boolean, p: string, tif: Record<string, unknown>, r = true) => ({
    a: 0,
    b,
    p,
    s: "0.01",
    r,
    t: tif,
    c: `0x${"1".repeat(32)}`,
  })
  const trigger = (tpsl: "tp" | "sl", triggerPx: string) => ({ trigger: { isMarket: true, triggerPx, tpsl } })
  /** A long market open at a 60000 mid with a TP at 66000 and an SL at 57000, priced as the API prices them. */
  const openWith = (side: "long" | "short", tpPx: string, slPx: string) => {
    const long = side === "long"
    const action = {
      type: "order",
      orders: [
        order(long, long ? "60600" : "59400", { limit: { tif: "Ioc" } }, false),
        order(!long, tpPx, trigger("tp", long ? "66000" : "54000")),
        order(!long, slPx, trigger("sl", long ? "57000" : "63000")),
      ],
      grouping: "normalTpsl",
      builder: { b: BUILDER, f: 100 },
    }
    const intent = {
      method: "open" as const,
      params: {
        coin: "BTC",
        side,
        size: "0.01",
        takeProfit: long ? "66000" : "54000",
        stopLoss: long ? "57000" : "63000",
      },
    }
    return verifyPerpsBuild(orderBuild({}, action), { builder: BUILDER, intent })
  }

  test("legs at the API's 500 bps from their triggers pass, long and short", () => {
    expect(openWith("long", "62700", "54150")).toEqual({ ok: true, kind: "l1" })
    expect(openWith("short", "56700", "66150")).toEqual({ ok: true, kind: "l1" })
  })

  test("a sell leg priced far below its trigger, or a buy leg far above, is refused", () => {
    for (const result of [
      openWith("long", "1", "54150"),
      openWith("long", "62700", "53000"),
      openWith("short", "56700", "99999"),
      openWith("short", "60000", "66150"),
    ]) {
      expect(result.ok).toBe(false)
      expect(result.ok ? "" : result.reason).toContain("slippage of the trigger price")
    }
  })

  test("the bound follows the API's default maximum slippage", () => {
    const file = join(import.meta.dir, "..", "..", "..", "apps", "api", "src", "lib", "perps-gate.ts")
    if (!existsSync(file)) return
    expect(readFileSync(file, "utf8")).toContain(
      `envInt(env.HYPERLIQUID_MAX_SLIPPAGE_BPS, ${HYPERLIQUID_TPSL_SLIPPAGE_BPS},`,
    )
  })
})

describe("setup's builder approval", () => {
  const nonce = 1_790_000_000_001
  const honest: PerpsBuildToVerify = {
    network: "mainnet",
    nonce,
    typedData: hyperliquidApproveBuilderFeeTypedData(BUILDER, nonce),
    action: {
      type: "approveBuilderFee",
      hyperliquidChain: "Mainnet",
      signatureChainId: "0xa4b1",
      maxFeeRate: "0.1%",
      builder: BUILDER,
      nonce,
    },
  }
  test("Candle's builder at 0.1% on Mainnet passes", () => {
    expect(verifyPerpsBuild(honest, { builder: BUILDER })).toEqual({ ok: true, kind: "approveBuilderFee" })
  })
  test("another builder, another rate, Testnet, or an action that differs from its typed data", () => {
    expect(
      verifyPerpsBuild(
        { ...honest, typedData: hyperliquidApproveBuilderFeeTypedData(OTHER, nonce) },
        { builder: BUILDER },
      ).ok,
    ).toBe(false)
    const rate = { ...honest.typedData, message: { ...honest.typedData.message, maxFeeRate: "1%" } }
    expect(verifyPerpsBuild({ ...honest, typedData: rate }, { builder: BUILDER }).ok).toBe(false)
    const testnet = { ...honest.typedData, message: { ...honest.typedData.message, hyperliquidChain: "Testnet" } }
    expect(verifyPerpsBuild({ ...honest, typedData: testnet }, { builder: BUILDER }).ok).toBe(false)
    expect(verifyPerpsBuild({ ...honest, action: { ...honest.action, builder: OTHER } }, { builder: BUILDER }).ok).toBe(
      false,
    )
  })
})

describe("submission", () => {
  test("splits a 65-byte signature, normalizing v", () => {
    const sig = `0x${"a".repeat(64)}${"b".repeat(64)}01`
    expect(hyperliquidSplitSignature(sig)).toEqual({ r: `0x${"a".repeat(64)}`, s: `0x${"b".repeat(64)}`, v: 28 })
    expect(() => hyperliquidSplitSignature("0x1234")).toThrow()
  })
  test("the exchange body and relay body", () => {
    const sig = `0x${"a".repeat(64)}${"b".repeat(64)}1b`
    expect(hyperliquidExchangeBody({ type: "cancel" }, 5, sig)).toEqual({
      action: { type: "cancel" },
      nonce: 5,
      signature: { r: `0x${"a".repeat(64)}`, s: `0x${"b".repeat(64)}`, v: 27 },
      vaultAddress: null,
      expiresAfter: null,
    })
    const typed = hyperliquidL1TypedData(`0x${"0".repeat(64)}`, "mainnet")
    expect(hyperliquidRelayBody(typed)).toEqual({ method: "eth_signTypedData_v4", params: { typed_data: typed } })
    expect(HYPERLIQUID_EXCHANGE_URLS.mainnet).toBe("https://api.hyperliquid.xyz/exchange")
  })
})

// Spec 2026-10-17 C, section 8: an order carrying the caller's client order id. The vectors are the
// official Python SDK's own (the cloid is an ordinary field of the order wire), so the hash these
// builds commit to is the venue's; what is added is the pre-sign binding of the id to the request.
describe("client order ids, against the official SDK vectors", () => {
  const vector = (name: string) => {
    const found = l1.find((c) => c.name === name)
    if (!found) throw new Error(`no vector ${name}`)
    return found
  }
  const buildOf = (v: L1Vector, action = v.action): PerpsBuildToVerify => ({
    network: "mainnet",
    nonce: v.nonce,
    action,
    typedData: hyperliquidL1TypedData(hyperliquidActionHash(v.action, v.nonce), "mainnet"),
  })

  test("an open with take-profit and stop-loss whose primary cloid is the caller's id passes", () => {
    const v = vector("order_normal_tpsl")
    expect(hyperliquidActionHash(v.action, v.nonce)).toBe(v.actionHash)
    const params = {
      coin: "BTC",
      side: "long",
      size: "0.01",
      price: "60000",
      takeProfit: "66000",
      stopLoss: "57000.5",
      clientId: "0x11111111111111111111111111111111",
    }
    const check = verifyPerpsBuild(buildOf(v), { builder: BUILDER, intent: { method: "open", params } })
    expect(check).toEqual({ ok: true, kind: "l1" })
    // Upper-case input normalizes to the same id.
    expect(
      verifyPerpsBuild(buildOf(v), {
        builder: BUILDER,
        intent: { method: "open", params: { ...params, clientId: params.clientId.toUpperCase().replace("0X", "0x") } },
      }).ok,
    ).toBe(true)
  })

  test("a reduce-only close whose cloid is the caller's id passes", () => {
    const v = vector("order_ioc_reduce_only_close")
    expect(hyperliquidActionHash(v.action, v.nonce)).toBe(v.actionHash)
    const check = verifyPerpsBuild(buildOf(v), {
      builder: BUILDER,
      intent: { method: "close", params: { coin: "SOL", clientId: "0x000102030405060708090a0b0c0d0e0f" } },
    })
    expect(check).toEqual({ ok: true, kind: "l1" })
  })

  test("an altered or missing id is refused before signing", () => {
    const v = vector("order_normal_tpsl")
    const params = { coin: "BTC", side: "long", size: "0.01", price: "60000", takeProfit: "66000", stopLoss: "57000.5" }
    for (const clientId of ["0x22222222222222222222222222222222", "0x1111", "not-hex", 7]) {
      const check = verifyPerpsBuild(buildOf(v), {
        builder: BUILDER,
        intent: { method: "open", params: { ...params, clientId } },
      })
      expect(check.ok).toBe(false)
    }
    // The build's id altered to the request's would no longer match the stamped hash.
    const action = structuredClone(v.action) as { orders: { c: string }[] }
    ;(action.orders[0] as { c: string }).c = "0x99999999999999999999999999999999"
    const forged = verifyPerpsBuild(
      { ...buildOf(v), action },
      {
        builder: BUILDER,
        intent: { method: "open", params: { ...params, clientId: "0x99999999999999999999999999999999" } },
      },
    )
    expect(forged).toEqual({ ok: false, reason: "the typed data does not commit to this action and nonce" })
  })

  test("a child leg reusing the primary id is refused", () => {
    const v = vector("order_normal_tpsl")
    const action = structuredClone(v.action) as { orders: { c: string }[] }
    ;(action.orders[1] as { c: string }).c = "0x11111111111111111111111111111111"
    const nonce = v.nonce
    const check = verifyPerpsBuild(
      {
        network: "mainnet",
        nonce,
        action,
        typedData: hyperliquidL1TypedData(hyperliquidActionHash(action, nonce), "mainnet"),
      },
      {
        builder: BUILDER,
        intent: {
          method: "open",
          params: {
            coin: "BTC",
            side: "long",
            size: "0.01",
            price: "60000",
            takeProfit: "66000",
            stopLoss: "57000.5",
            clientId: "0x11111111111111111111111111111111",
          },
        },
      },
    )
    expect(check).toEqual({ ok: false, reason: "the order legs do not carry distinct client order ids" })
  })

  test("without a client id the check is unchanged", () => {
    const v = vector("order_ioc_reduce_only_close")
    expect(
      verifyPerpsBuild(buildOf(v), { builder: BUILDER, intent: { method: "close", params: { coin: "SOL" } } }).ok,
    ).toBe(true)
  })
})

describe("setup: account mode and the setup answer", () => {
  const ADDR = "0x00000000000000000000000000000000000000aa"
  const status = (over: Record<string, unknown> = {}) => ({
    walletId: "w1",
    address: ADDR,
    network: "mainnet",
    mode: "default",
    standardMode: true,
    accountValue: "10",
    withdrawable: "10",
    builder: BUILDER,
    approvedFeeTenthsBps: 100,
    ready: true,
    ...over,
  })
  const expectOk = { network: "mainnet" as const, address: ADDR, builder: BUILDER, mode: "default" }

  test("only default and disabled are standard", () => {
    expect(HYPERLIQUID_STANDARD_ACCOUNT_MODES).toEqual(["default", "disabled"])
    expect(perpsSetupStatusProblem(status(), expectOk)).toBeNull()
    expect(perpsSetupStatusProblem(status({ mode: "disabled" }), { ...expectOk, mode: "disabled" })).toBeNull()
    for (const mode of ["unifiedAccount", "portfolioMargin", "dexAbstraction", "somethingNew"]) {
      expect(perpsSetupStatusProblem(status({ mode }), { ...expectOk, mode })).toContain(`${mode} mode`)
    }
  })

  test("a dishonest ready answer is rejected", () => {
    expect(perpsSetupStatusProblem(status({ mode: "default" }), { ...expectOk, mode: "unifiedAccount" })).toContain(
      "unifiedAccount",
    )
    expect(perpsSetupStatusProblem(status({ mode: "disabled" }), expectOk)).toBe(
      "the setup answer reports a mode Hyperliquid does not",
    )
    expect(perpsSetupStatusProblem(status({ builder: OTHER }), expectOk)).toBe(
      "the setup answer names a builder that is not Candle's",
    )
    expect(perpsSetupStatusProblem(status({ address: OTHER }), expectOk)).toBe(
      "the setup answer is for a different wallet",
    )
    expect(perpsSetupStatusProblem(status({ network: "testnet" }), expectOk)).toBe("the setup answer is for testnet")
    expect(perpsSetupStatusProblem(status({ standardMode: false }), expectOk)).toBe(
      "the setup answer does not report standard mode",
    )
    expect(perpsSetupStatusProblem(status({ approvedFeeTenthsBps: 10 }), expectOk)).toBe(
      "the setup answer reports ready without Candle's builder approval",
    )
    // A not-ready answer needs no approval yet.
    expect(perpsSetupStatusProblem(status({ ready: false, approvedFeeTenthsBps: 0 }), expectOk)).toBeNull()
  })

  test("the mode is read from the pinned venue's userAbstraction", async () => {
    const calls: { url: string; body: unknown }[] = []
    const fetcher = async (url: string, init?: RequestInit) => {
      calls.push({ url, body: JSON.parse(String(init?.body)) })
      return new Response(JSON.stringify("portfolioMargin"))
    }
    expect(await hyperliquidAccountMode(fetcher, "mainnet", ADDR.toUpperCase().replace("0X", "0x"))).toBe(
      "portfolioMargin",
    )
    expect(calls).toEqual([{ url: "https://api.hyperliquid.xyz/info", body: { type: "userAbstraction", user: ADDR } }])
    const broken = async () => new Response(JSON.stringify({ mode: "default" }))
    expect(hyperliquidAccountMode(broken, "mainnet", ADDR)).rejects.toThrow("unreadable account mode")
    const down = async () => new Response("no", { status: 500 })
    expect(hyperliquidAccountMode(down, "mainnet", ADDR)).rejects.toThrow("Cannot read the account mode")
  })
})
