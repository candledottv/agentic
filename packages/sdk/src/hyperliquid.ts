// ── msgpack, exactly as Python's msgpack.packb encodes the types an action uses ──────────────

const UINT64_MAX = (1n << 64n) - 1n
const INT64_MIN = -(1n << 63n)

function pushUint(out: number[], value: bigint, width: number): void {
  for (let i = width - 1; i >= 0; i--) out.push(Number((value >> BigInt(i * 8)) & 0xffn))
}

function packInteger(out: number[], value: bigint): void {
  if (value >= 0n) {
    if (value > UINT64_MAX) throw new Error("msgpack: integer above uint64")
    if (value < 0x80n) out.push(Number(value))
    else if (value <= 0xffn) {
      out.push(0xcc)
      pushUint(out, value, 1)
    } else if (value <= 0xffffn) {
      out.push(0xcd)
      pushUint(out, value, 2)
    } else if (value <= 0xffffffffn) {
      out.push(0xce)
      pushUint(out, value, 4)
    } else {
      out.push(0xcf)
      pushUint(out, value, 8)
    }
    return
  }
  if (value < INT64_MIN) throw new Error("msgpack: integer below int64")
  if (value >= -32n) out.push(Number(value & 0xffn))
  else if (value >= -128n) {
    out.push(0xd0)
    pushUint(out, value & 0xffn, 1)
  } else if (value >= -32768n) {
    out.push(0xd1)
    pushUint(out, value & 0xffffn, 2)
  } else if (value >= -2147483648n) {
    out.push(0xd2)
    pushUint(out, value & 0xffffffffn, 4)
  } else {
    out.push(0xd3)
    pushUint(out, value & UINT64_MAX, 8)
  }
}

function packHeader(out: number[], length: number, fixBase: number, fixMax: number, codes: number[]): void {
  if (length <= fixMax) {
    out.push(fixBase | length)
    return
  }
  const [c8, c16, c32] = codes
  if (c8 !== undefined && c8 !== 0 && length <= 0xff) {
    out.push(c8)
    pushUint(out, BigInt(length), 1)
  } else if (length <= 0xffff) {
    out.push(c16 as number)
    pushUint(out, BigInt(length), 2)
  } else {
    out.push(c32 as number)
    pushUint(out, BigInt(length), 4)
  }
}

function packValue(out: number[], value: unknown): void {
  if (value === null) out.push(0xc0)
  else if (value === false) out.push(0xc2)
  else if (value === true) out.push(0xc3)
  else if (typeof value === "bigint") packInteger(out, value)
  else if (typeof value === "number") {
    // An action never carries a float: prices and sizes are decimal strings.
    if (!Number.isSafeInteger(value)) throw new Error(`msgpack: ${value} is not a safe integer`)
    packInteger(out, BigInt(value))
  } else if (typeof value === "string") {
    const bytes = new TextEncoder().encode(value)
    packHeader(out, bytes.length, 0xa0, 31, [0xd9, 0xda, 0xdb])
    for (const b of bytes) out.push(b)
  } else if (Array.isArray(value)) {
    packHeader(out, value.length, 0x90, 15, [0, 0xdc, 0xdd])
    for (const item of value) packValue(out, item)
  } else if (typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>).filter(([, v]) => v !== undefined)
    for (const [key] of entries) {
      // JavaScript enumerates integer-like keys first; no action key is one.
      if (/^(0|[1-9][0-9]*)$/.test(key)) throw new Error(`msgpack: integer-like key "${key}"`)
    }
    packHeader(out, entries.length, 0x80, 15, [0, 0xde, 0xdf])
    for (const [key, item] of entries) {
      packValue(out, key)
      packValue(out, item)
    }
  } else {
    throw new Error(`msgpack: cannot encode a ${typeof value}`)
  }
}

/** Python `msgpack.packb(value)` for the JSON-like values an action uses. Throws on anything else. */
export function msgpackEncode(value: unknown): Uint8Array {
  const out: number[] = []
  packValue(out, value)
  return Uint8Array.from(out)
}

function toHex(bytes: Uint8Array): string {
  let out = ""
  for (const b of bytes) out += b.toString(16).padStart(2, "0")
  return out
}

/** The official SDK's `action_hash(action, None, nonce, None)`, as `0x` + 64 hex. */
export function hyperliquidActionHash(action: unknown, nonce: number | bigint): string {
  const n = BigInt(nonce)
  if (n < 0n || n > UINT64_MAX) throw new Error("hyperliquidActionHash: nonce out of range")
  const out = Array.from(msgpackEncode(action))
  pushUint(out, n, 8)
  out.push(0)
  return `0x${toHex(keccak_256(Uint8Array.from(out)))}`
}

