/** A 65-byte `0x` signature split the way `/exchange` takes it. */
export function hyperliquidSplitSignature(signature: string): { r: string; s: string; v: number } {
  if (!/^0x[0-9a-fA-F]{130}$/.test(signature)) throw new Error("Not a 65-byte signature")
  let v = Number.parseInt(signature.slice(130, 132), 16)
  if (v < 27) v += 27
  return { r: `0x${signature.slice(2, 66)}`, s: `0x${signature.slice(66, 130)}`, v }
}

/** The `/exchange` request body for a signed action. */
export function hyperliquidExchangeBody(action: Record<string, unknown>, nonce: number, signature: string) {
  return { action, nonce, signature: hyperliquidSplitSignature(signature), vaultAddress: null, expiresAfter: null }
}

/** The relay body (Privy's wallet-RPC wire shape) for typed data. */
export function hyperliquidRelayBody(typedData: HyperliquidTypedData) {
  return { method: "eth_signTypedData_v4" as const, params: { typed_data: typedData } }
}
