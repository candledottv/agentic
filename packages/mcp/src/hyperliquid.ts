/**
 * Hyperliquid perps (Candle spec 2026-10-01-hyperliquid-perps-tee-design.md, HL-ED-2, HL-ED-5): the
 * client half of "Candle builds each action, the client submits it".
 *
 * A perps build route returns a plaintext Hyperliquid action, the nonce, and the EIP-712 typed data
 * Candle stamped a relay claim over. Before anything is signed, the client recomputes the action
 * hash from the plaintext and checks it is the hash inside the typed data, that the action type is
 * one of the five Candle builds, that the builder is Candle's (or absent on a Max order), and that
 * the typed data is exactly one of the two shapes the relay forwards. Only then does it ask the
 * relay to sign, and it submits the signed action to Hyperliquid itself. A mismatch is a client
 * refusal, with no relay call. This is what stops a dishonest build: the TEE wallet signs only a
 * hash, so nothing downstream can read the action back.
 *
 * The encoding is the official Python SDK's `action_hash` (msgpack of the action, the nonce as
 * 8 big-endian bytes, a zero byte for "no vault", keccak-256), byte for byte:
 * `hyperliquid.vectors.fixture.json` holds vectors generated by that SDK, and `hyperliquid.test.ts`
 * reproduces every one.
 *
 * `packages/cli/src/hyperliquid.ts` and `packages/mcp/src/hyperliquid.ts` are byte-identical copies
 * of this file (drift tests enforce it), and the Candle API carries the same encoder. Self-contained
 * on purpose: its only import is keccak.
 */
import { keccak_256 } from "@noble/hashes/sha3"

